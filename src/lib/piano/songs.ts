function preludeBar(
  start: number,
  lh: Array<[number, Finger]>,
  rh: Array<[number, Finger]>,
): ScoreNote[] {
  const out: ScoreNote[] = [];
  const six = 0.25;
  for (let rep = 0; rep < 2; rep++) {
    const t0 = start + rep * 2;
    lh.forEach(([p, f], i) => out.push(n(p, t0 + i * six, six, "L", f, 0.56)));
    rh.forEach(([p, f], i) => out.push(n(p, t0 + (lh.length + i) * six, six, "R", f, 0.7)));
  }
  return out;
}

