export type SongLevel = "beginner" | "intermediate" | "advanced";
export type SongCategory = "all" | "pop_ost" | "classic" | "practice";

export interface DemoSong {
  id: string;
  title: string;
  titleKo: string;
  composer: string;
  bpm: number;
  timeSignature: [number, number];
  description: string;
  teach: string;
  level: SongLevel;
  category: "pop_ost" | "classic" | "practice";
  notes: ScoreNote[];
}

let nid = 0;
function n(
  pitch: number,
  start: number,
  duration: number,
  hand: HandId,
  finger: Finger,
  velocity = 0.78,
): ScoreNote {
  nid += 1;
  return {
    id: `d${nid}`,
    pitch,
    start,
    duration,
    velocity,
    track: hand === "R" ? 0 : 1,
    hand,
    finger,
  };
}

function seq(
  hand: HandId,
  start: number,
  items: Array<[pitch: number, finger: Finger, duration?: number, velocity?: number]>,
): ScoreNote[] {
  let t = start;
  const out: ScoreNote[] = [];
  for (const [pitch, finger, duration = 1, velocity] of items) {
    out.push(n(pitch, t, duration, hand, finger, velocity));
    t += duration;
  }
  return out;
}

function chord(
  pitches: Array<[number, Finger]>,
  start: number,
  duration: number,
  hand: HandId,
  velocity = 0.7,
): ScoreNote[] {
  return pitches.map(([pitch, finger]) => n(pitch, start, duration, hand, finger, velocity));
}

